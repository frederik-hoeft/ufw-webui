        Assert.AreEqual(0, (await InvokeUfwAsync("--force", "enable")).ExitCode);
        string defaults = Path.Combine(_directory, "defaults");
        string baseline = InvokeSave(FirewallAddressFamily.IPv6, "-t", "filter").StdOut;
        Assert.Contains(":ufw6-user-input", baseline);

        await File.WriteAllTextAsync(defaults, "IPV6=no\n");
        Assert.AreEqual(baseline, InvokeSave(FirewallAddressFamily.IPv6, "-t", "filter").StdOut,
            "Changing configuration files does not change installed netfilter rules.");
        Assert.AreEqual(0, (await InvokeUfwAsync("allow", "in", "from", "0.0.0.0/0", "to", "0.0.0.0/0", "port", "8080", "proto", "tcp")).ExitCode);
        Assert.AreEqual(baseline, InvokeSave(FirewallAddressFamily.IPv6, "-t", "filter").StdOut,
            "Even a UFW IPv4 mutation must not implicitly apply a pending IPv6 configuration change.");
        Assert.AreEqual(0, (await InvokeUfwAsync("reload")).ExitCode);
        (int code, string save, _) = InvokeSave(FirewallAddressFamily.IPv6, "-t", "filter");
        Assert.AreEqual(0, code);
        Assert.IsTrue(IptablesSaveGrammar.Instance.TryParse(save, FirewallAddressFamily.IPv6, out RawFilterTable? inactiveV6));
        Assert.IsFalse(inactiveV6.Chains.Any(static chain => chain.Name == "ufw6-user-input"));
        Assert.AreEqual(FilterChainPolicy.Drop, inactiveV6.Chains.Single(static chain => chain.Name == "INPUT").Policy);
        Assert.AreEqual(FilterChainPolicy.Drop, inactiveV6.Chains.Single(static chain => chain.Name == "OUTPUT").Policy);
        Assert.AreEqual(FilterChainPolicy.Drop, inactiveV6.Chains.Single(static chain => chain.Name == "FORWARD").Policy);
        Assert.AreEqual("ACCEPT", inactiveV6.Chains.Single(static chain => chain.Name == "INPUT").Rules.Single().Target.Name);
        Assert.Contains("--dport 22", await File.ReadAllTextAsync(Path.Combine(_directory, "user6.rules")));

        await File.WriteAllTextAsync(defaults, "IPV6=yes\n");
        Assert.AreEqual(save, InvokeSave(FirewallAddressFamily.IPv6, "-t", "filter").StdOut);
        Assert.AreEqual(0, (await InvokeUfwAsync("reload")).ExitCode);
        (code, save, _) = InvokeSave(FirewallAddressFamily.IPv6, "-t", "filter");
        Assert.AreEqual(0, code);
        Assert.IsTrue(IptablesSaveGrammar.Instance.TryParse(save, FirewallAddressFamily.IPv6, out RawFilterTable? enabledV6));
        Assert.HasCount(1, enabledV6.Chains.Single(static chain => chain.Name == "ufw6-user-input").Rules);
    }

    [TestMethod]
    public async Task RestoreFixturesAreSnapshottedUntilReloadAndApplyNoflushChainSemanticsAsync()
    {
        string fixture = Path.Combine(_directory, "before.rules");
        await File.WriteAllTextAsync(fixture, """
            *nat
            :PREROUTING ACCEPT [0:0]
            COMMIT
            *filter
            :INPUT DROP [0:0]
            :ufw-before-input - [0:0]
            :external-guard - [0:0]
            -A INPUT -p tcp --dport 1234 -j DROP
            -A ufw-before-input -j external-guard
            -A external-guard -j RETURN
            COMMIT
            """);
        SetEnvironment("UFW_MOCK_IPTABLES4_BEFORE_FILES", fixture);
        Assert.AreEqual(0, (await InvokeUfwAsync("--force", "enable")).ExitCode);
        string installed = InvokeSave(FirewallAddressFamily.IPv4, "-t", "filter").StdOut;
        Assert.Contains(":INPUT DROP", installed);
        Assert.Contains("-A INPUT -p tcp --dport 1234 -j DROP", installed);
        Assert.Contains("-A ufw-before-input -j external-guard", installed);
        Assert.IsFalse(installed.Contains("-A ufw-before-input -i lo", StringComparison.Ordinal),
            "Under iptables-restore -n, redeclaring an existing user chain flushes it.");
        Assert.Contains("-A ufw-before-input -j ufw-user-input", installed);

        await File.WriteAllTextAsync(fixture, """
            *filter
            :INPUT ACCEPT [0:0]
            :external-guard - [0:0]
            -A INPUT -p tcp --dport 4321 -j DROP
            COMMIT
            """);
        Assert.AreEqual(installed, InvokeSave(FirewallAddressFamily.IPv4, "-t", "filter").StdOut);
        Assert.AreEqual(0, (await InvokeUfwAsync("allow", "443/tcp")).ExitCode);
        string afterRuleUpdate = InvokeSave(FirewallAddressFamily.IPv4, "-t", "filter").StdOut;
        Assert.Contains("-A INPUT -p tcp --dport 1234 -j DROP", afterRuleUpdate);
        Assert.IsFalse(afterRuleUpdate.Contains("--dport 4321", StringComparison.Ordinal));

        Assert.AreEqual(0, (await InvokeUfwAsync("reload")).ExitCode);
        string reloaded = InvokeSave(FirewallAddressFamily.IPv4, "-t", "filter").StdOut;
        Assert.Contains("-A INPUT -p tcp --dport 4321 -j DROP", reloaded);
        Assert.IsFalse(reloaded.Contains("--dport 1234", StringComparison.Ordinal));
        Assert.Contains(":INPUT ACCEPT", reloaded);

        // UFW stop must not drop unrelated host rules just because they aren't managed by UFW.
        Assert.AreEqual(0, (await InvokeUfwAsync("disable")).ExitCode);
        string stopped = InvokeSave(FirewallAddressFamily.IPv4, "-t", "filter").StdOut;
        Assert.Contains("-A INPUT -p tcp --dport 4321 -j DROP", stopped);
        Assert.IsFalse(stopped.Contains(":ufw-before-input", StringComparison.Ordinal));
    }

